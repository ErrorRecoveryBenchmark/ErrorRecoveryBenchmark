#!/usr/bin/env python3
"""Configure local display support for the pinned robosuite on Windows/macOS."""
import argparse
import importlib.metadata
import importlib.util
import platform
import shutil
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--robosuite-dir", type=Path, default=Path(__file__).resolve().parents[1] / "shared/mimicgen_workspace/robosuite/robosuite")
    args = parser.parse_args()
    if platform.system() not in {"Windows", "Darwin"}:
        print("Linux: choose MUJOCO_GL=egl for headless GPU or configure GLFW for a display.")
        return
    if importlib.metadata.version("mujoco") != "2.3.2":
        parser.error("This repository requires mujoco==2.3.2; refusing to configure another version")
    if not (args.robosuite_dir / "macros.py").is_file():
        parser.error("Initialize the pinned robosuite submodule first")
    macros = args.robosuite_dir / "macros_private.py"
    if not macros.exists():
        macros.write_text("# Local display configuration; generated by RecoverBench.\nMUJOCO_GPU_RENDERING = False\n", encoding="utf-8")
    elif "MUJOCO_GPU_RENDERING = False" not in macros.read_text():
        parser.error("Existing macros_private.py does not disable forced GPU rendering; preserve your other settings and set MUJOCO_GPU_RENDERING = False")
    if platform.system() == "Windows":
        spec = importlib.util.find_spec("mujoco")
        dll = Path(next(iter(spec.submodule_search_locations))) / "mujoco.dll"
        if not dll.is_file():
            parser.error(f"Pinned MuJoCo DLL not found: {dll}")
        target = args.robosuite_dir / "utils/mujoco.dll"
        if not target.exists():
            shutil.copy2(dll, target)
    print("Local simulator support configured. Set MUJOCO_GL=glfw before running.")


if __name__ == "__main__":
    main()
